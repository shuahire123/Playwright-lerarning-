import { test, expect } from "@playwright/test";

/* Test Case 1: Chrome CPU Load Validation
Objective:
Verify Chrome CPU load in the table matches the value in the red label.

Test Steps:
1. Verify the page loads successfully.
2. Verify the task table is displayed.
3. Verify the table contains multiple rows.
4. Verify each row has a process name column.
5. Identify the row where process name = Chrome.
6. Extract the CPU load value (should contain %).
7. Verify the CPU load value is not empty.
8. Verify the red label (strong.chrome-cpu) is visible.
9. Verify the red label value matches the extracted CPU load.
10. Verify only one Chrome row exists (or handle multiple correctly). */
test("Test Case 1: Chrome CPU Load Validation", async ({ page }) => {
  await test.step("1. Verify the page loads successfully", async () => {
    await page.goto("https://sdetqa.vercel.app/autoplay");
    await expect(page).toHaveTitle("Web Automation Playground");
  });

  const taskTable = page.locator("#taskTable");

  await test.step("2. Verify the task table is displayed", async () => {
    await expect(taskTable).toBeVisible();
  });

  await test.step("3. Verify the table contains multiple rows", async () => {
    await expect(taskTable.locator("tbody tr")).toHaveCount(4);
  });

  await test.step("4. Verify each row has a process name", async () => {
    const nameCells = taskTable.locator("tbody tr td:nth-child(1)");
    await expect(nameCells).toHaveCount(4);
    for (const cell of await nameCells.all()) {
      await expect(cell).not.toHaveText(/^\s*$/);
    }
  });

  // Columns are shuffled on every page load, so locate the CPU column by header name.
  const headerTexts = await taskTable.locator("thead th").allTextContents();
  const cpuColumnIndex = headerTexts.findIndex((text) => text.trim() === "CPU (%)");
  expect(cpuColumnIndex, "CPU column should exist in the table header").toBeGreaterThan(0);

  let cpuLoad = "";

  await test.step("5-7. Find the Chrome row and read a non-empty CPU value", async () => {
    const chromeRows = taskTable.locator("tbody tr").filter({ hasText: "Chrome" });
    await expect(chromeRows).toHaveCount(1); // step 10: only one Chrome row

    const cpuCell = chromeRows.locator("td").nth(cpuColumnIndex);
    cpuLoad = ((await cpuCell.textContent()) ?? "").trim();

    expect(cpuLoad).not.toBe("");
    expect(cpuLoad).toMatch(/^\d+(\.\d+)?%$/); // step 6: must contain %
  });

  await test.step("8-9. Verify the label is visible and matches the table", async () => {
    const chromeCpuLabel = page.locator("strong.chrome-cpu").first();
    await expect(chromeCpuLabel).toBeVisible();
    await expect(chromeCpuLabel).toHaveText(cpuLoad);
  });
});
/* Test Case 2: Firefox Memory Usage Validation
Objective:
Verify Firefox memory usage in the table matches the value in the blue label.
Test Steps:
1. Verify the page loads successfully.
2. Verify the table is present.
3. Identify the row where process name = Firefox.
4. Extract memory value ending with MB.
5. Verify extracted value matches pattern (e.g., \d+ MB).
6. Verify memory value is not empty.
7. Verify blue label (strong.firefox-memory) is visible.
8. Compare extracted memory with label value.
9. Validate case sensitivity of process name (Firefox vs firefox). */
test("Test Case 2: Firefox Memory Usage Validation", async ({ page }) => {
  await test.step("1. Verify the page loads successfully", async () => {
    await page.goto("https://sdetqa.vercel.app/autoplay");
    await expect(page).toHaveTitle("Web Automation Playground");
  });

  const taskTable = page.locator("#taskTable");

  await test.step("2. Verify the task table is displayed", async () => {
    await expect(taskTable).toBeVisible();
    // FIX: also assert the table is populated. The rows are generated by
    // createTable() on DOMContentLoaded, so visibility alone is not enough.
    await expect(taskTable.locator("tbody tr")).toHaveCount(4);
  });

  // FIX: search only the header row ("thead th") instead of every "th".
  const headers = await taskTable.locator("thead th").allTextContents();
  const memoryColumnIndex = headers.findIndex(
    (header) => header.trim() === "Memory (MB)",
  );
  // FIX: findIndex returns -1 when the column is missing. checking "> 0" only
  // worked by luck because "Name" is always the first header. Check absence.
  expect(memoryColumnIndex, "Memory (MB) column should exist").not.toBe(-1);

  // FIX: the old filter({ hasText: "FireFox" }) did NOT validate case
  // sensitivity. Playwright's string hasText match is case-insensitive, so it
  // matched "Firefox" anyway. Match the process-name cell exactly instead.
   const chromeRows = taskTable.locator("tbody tr").filter({ hasText: "Chrome" });
  const firefoxRows = taskTable.locator("tbody tr").filter({
    has: page.getByRole("cell", { name: "Firefox", exact: true }),
  });

  await test.step("3 + 9. Find exactly one row named 'Firefox'", async () => {
    await expect(firefoxRows).toHaveCount(1);
  });

  let firefoxMemory = "";

  await test.step("4-6. Extract and validate the memory value", async () => {
    // FIX: the old code did fireFoxRow.nth(indexOfFF), which selected the Nth
    // ROW (there is only one Firefox row) instead of the Nth CELL, so it always
    // timed out waiting for a non-existent row. Select the cell inside the row.
    const memoryCell = firefoxRows.locator("td").nth(memoryColumnIndex);
    firefoxMemory = (await memoryCell.innerText()).trim();

    // FIX: trim before checking emptiness so whitespace-only values fail.
    expect(firefoxMemory, "Memory value should not be empty").not.toBe("");
    // FIX: step 5's format validation was missing entirely.
    expect(firefoxMemory).toMatch(/^\d+(\.\d+)? MB$/);
  });

  await test.step("7-8. Verify the label is visible and matches the table", async () => {
    // FIX: use the documented selector strong.firefox-memory and .first()
    // instead of the loose .firefox-memory + .nth(0).
    const firefoxMemoryLabel = page.locator("strong.firefox-memory").first();
    await expect(firefoxMemoryLabel).toBeVisible();
    // FIX: toHaveText auto-retries; comparing two raw textContent() strings
    // with toBe could flake if the label renders slightly later.
    await expect(firefoxMemoryLabel).toHaveText(firefoxMemory);
  });
});
